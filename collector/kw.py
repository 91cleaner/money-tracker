"""제목 키워드 매칭: 단순 부분 문자열로 잡으면 틀리는 경우를 막는다.
예) '청소' ⊂ '청소년', '보안' ⊂ '보안등'·'버스정보안내기', '제초' ⊂ '통제초소', '행사' ⊂ '대행사업'·'이행사업',
'소방' ⊂ '○○소방서'(기관 이름), '시설관리' ⊂ '○○시설관리공단'(기관 이름)."""
import re

_RX = {
    "청소": r"청소(?!년)",
    "보안": r"(?<!정)보안(?!등)",
    "제초": r"(?<!통)제초(?!소)",
    "행사": r"(?<![대이])행사",
    "소방": r"소방(?!서|본부|도로)",
    "시설관리": r"시설관리(?!공단)",
    "인쇄": r"(?<!고)인쇄",
    "기기": r"(?<!동)기기",
}
_C = {k: re.compile(v) for k, v in _RX.items()}


def hit(title, w):
    t = title or ""
    c = _C.get(w)
    return bool(c.search(t)) if c else (w in t)
