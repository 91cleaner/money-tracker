def names(s):
    """행사·공연·강연 계약명에서 사람 이름을 ○○○로. 공원·파크골프장 이름, 역사 인물은 남김. 나라 세금(정치인)에는 쓰지 않음."""
    if not isinstance(s, str):
        return s
    s = _PAREN.sub(lambda m: "(○○○)" if _ok(m.group(1)) and _LAND.search(s[max(0, m.start() - 16):m.start()]) else m.group(0), s)  # '지장물 철거(홍길동)': 땅·보상 관련 괄호 속 개인 이름
    if not (_EV.search(s) or _TR2.search(s)):
        return s
    out, last = [], 0
    for m in _RX.finditer(s):
        p, w = m.group(1), m.group(2)
        ww = w
        if len(w) == 4 and not _ok(w) and w[-1] in "와과의님씨":
            ww = w[:3]
        if not _ok(ww):
            continue
        a = m.start() + len(p)
        pre, post = s[max(0, a - 10):a], s[a + len(ww):a + len(ww) + 10]
        if _PARK.search(post) or _CORP.search(pre) or re.match(r"^\s?(작가)?\s?기념", post):
            continue  # 장소(공원·파크골프장), 회사 이름, 기념시설(역사 인물)
        if _TR.search(pre) or _TR.search(post) or _SEP.search(pre[-2:]) or _SEP.search(post[:2]) or _TR2.search(post[:8]):
            out.append(s[last:a]); out.append("○○○"); last = a + len(ww)
    if not out:
        return s
    out.append(s[last:])
    return "".join(out)
