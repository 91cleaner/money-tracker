def _ok(w):
    if w in _STOP:
        return False
    return (_SUR.find(w[0]) >= 0 and w[2] not in _END) if len(w) == 3 else w[:2] in _S2


_PAREN = re.compile(r"\(([가-힣]{3})\)")
_LAND = re.compile(r"지장물|철거|보상|토지|매입|분묘|이장|감정평가|\(\d+차\)$")
_CORP = re.compile(r"(\(주\)|㈜|주식회사|\(유\)|유한회사)\s?$")
